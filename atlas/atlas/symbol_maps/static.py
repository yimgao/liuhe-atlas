# ===================
# 工具函数
# ===================
def get_all_attributes(ball_number: int, year: int = 2026) -> dict:
    """返回号码的完整符号属性"""
    attrs = {
        "ball": ball_number,
        "wuxing": WUXING_MAP.get(ball_number, "?"),
        "wave_color": WAVE_MAP.get(ball_number, "?"),
        "odd_even": ODD_EVEN_MAP.get(ball_number, "?"),
    }
    if year == 2026:
        attrs["zodiac"] = NUMBER_TO_ZODIAC_2026.get(ball_number, "?")
    return attrs

def get_zodiac_attributes(zodiac: str) -> dict:
    """返回生肖的民俗属性"""
    result = {}
    for attr, zodiacs in ZODIAC_ATTRIBUTES.items():
        if zodiac in zodiacs:
            result[attr] = True
        else:
            result[attr] = False
    return result

